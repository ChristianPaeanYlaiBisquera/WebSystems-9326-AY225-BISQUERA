"""
PDF Generator — GeeksforGeeks PHP Learning Module
Generates a professional academic handout PDF from scraped data.
"""

from reportlab.lib.pagesizes import A4
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import cm, mm
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle,
    PageBreak, HRFlowable, KeepTogether
)
from reportlab.lib.enums import TA_CENTER, TA_LEFT, TA_JUSTIFY
from reportlab.pdfgen import canvas
from datetime import datetime
import os

# ── Color palette ──────────────────────────────────────────────
GFG_GREEN    = colors.HexColor("#2F8D46")
GFG_DARK     = colors.HexColor("#1A5C2A")
GFG_LIGHT    = colors.HexColor("#E8F5E9")
GFG_ACCENT   = colors.HexColor("#F4A71D")
DARK_GRAY    = colors.HexColor("#2D2D2D")
MID_GRAY     = colors.HexColor("#555555")
LIGHT_GRAY   = colors.HexColor("#F5F5F5")
CODE_BG      = colors.HexColor("#1E1E1E")
CODE_FG      = colors.HexColor("#D4D4D4")
BORDER_COLOR = colors.HexColor("#C8E6C9")


# ── Page header/footer callback ────────────────────────────────
class PageTemplate:
    def __init__(self, student_name: str, total_articles: int):
        self.student_name = student_name
        self.total_articles = total_articles

    def __call__(self, canvas_obj, doc):
        canvas_obj.saveState()
        w, h = A4

        # ── Top header bar ──
        canvas_obj.setFillColor(GFG_GREEN)
        canvas_obj.rect(0, h - 28*mm, w, 28*mm, fill=1, stroke=0)

        # Header text
        canvas_obj.setFillColor(colors.white)
        canvas_obj.setFont("Helvetica-Bold", 13)
        canvas_obj.drawString(15*mm, h - 13*mm, "GeeksforGeeks")
        canvas_obj.setFont("Helvetica", 9)
        canvas_obj.drawString(15*mm, h - 20*mm, "PHP Programming — Learning Module")

        # Right side: date + subject
        canvas_obj.setFont("Helvetica", 8)
        date_str = datetime.now().strftime("%B %d, %Y")
        canvas_obj.drawRightString(w - 15*mm, h - 13*mm, f"Generated: {date_str}")
        canvas_obj.drawRightString(w - 15*mm, h - 20*mm, "Subject Category: PHP / Web Development")

        # ── Footer bar ──
        canvas_obj.setFillColor(GFG_DARK)
        canvas_obj.rect(0, 0, w, 14*mm, fill=1, stroke=0)

        canvas_obj.setFillColor(colors.white)
        canvas_obj.setFont("Helvetica", 7.5)
        canvas_obj.drawString(15*mm, 5*mm,
            f"Generated by {self.student_name}  |  Source: geeksforgeeks.org  |  {self.total_articles} Topics Covered")
        canvas_obj.setFont("Helvetica-Bold", 8)
        canvas_obj.drawRightString(w - 15*mm, 5*mm, f"Page {doc.page}")

        canvas_obj.restoreState()


