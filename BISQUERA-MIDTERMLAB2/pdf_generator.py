def difficulty_style(difficulty: str, styles: dict) -> ParagraphStyle:
    d = difficulty.lower()
    if "easy" in d or "basic" in d:
        return styles["difficulty_easy"]
    elif "medium" in d:
        return styles["difficulty_medium"]
    elif "hard" in d or "expert" in d:
        return styles["difficulty_hard"]
    return styles["difficulty_na"]


def section_label(text: str, styles: dict) -> list:
    """Returns a colored label row for a section."""
    return [
        HRFlowable(width="100%", thickness=0.5, color=BORDER_COLOR, spaceAfter=2),
        Paragraph(f"▸  {text}", styles["section_head"]),
    ]


def build_cover_page(story: list, styles: dict, student_name: str,
                     total: int, date_str: str):
    """Build a full cover page."""
    w, h = A4

    # Big green cover background via a table
    cover_data = [[
        Paragraph("GeeksforGeeks", styles["cover_title"]),
    ]]
    cover_table = Table(cover_data, colWidths=[w - 4*cm])
    cover_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), GFG_GREEN),
        ("TOPPADDING", (0, 0), (-1, -1), 60),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 20),
        ("LEFTPADDING", (0, 0), (-1, -1), 20),
        ("RIGHTPADDING", (0, 0), (-1, -1), 20),
        ("ROWBACKGROUNDS", (0, 0), (-1, -1), [GFG_GREEN]),
    ]))
    story.append(cover_table)

    # Sub info block
    info_data = [
        [Paragraph("PHP Programming", styles["cover_sub"])],
        [Paragraph("Learning Module &amp; Study Guide", styles["cover_sub"])],
        [Spacer(1, 8)],
        [Paragraph(f"Total Topics Covered: <b>{total}</b>", styles["cover_meta"])],
        [Paragraph(f"Date of Generation: <b>{date_str}</b>", styles["cover_meta"])],
        [Paragraph(f"Generated by: <b>{student_name}</b>", styles["cover_meta"])],
        [Paragraph("Source: geeksforgeeks.org", styles["cover_meta"])],
    ]
    info_table = Table(info_data, colWidths=[w - 4*cm])
    info_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), GFG_DARK),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
        ("LEFTPADDING", (0, 0), (-1, -1), 20),
        ("RIGHTPADDING", (0, 0), (-1, -1), 20),
        ("ALIGN", (0, 0), (-1, -1), "CENTER"),
    ]))
    story.append(info_table)
    story.append(PageBreak())


def build_toc(story: list, styles: dict, articles: list):
    """Build a Table of Contents page."""
    story.append(Spacer(1, 10*mm))
    story.append(Paragraph("Table of Contents", styles["toc_title"]))
    story.append(HRFlowable(width="100%", thickness=1.5, color=GFG_GREEN, spaceAfter=10))

    for i, art in enumerate(articles, 1):
        title = art.get("title", "Untitled")
        diff = art.get("difficulty", "Not Available")
        diff_color = "#2E7D32" if "easy" in diff.lower() or "basic" in diff.lower() \
            else "#E65100" if "medium" in diff.lower() \
            else "#B71C1C" if "hard" in diff.lower() \
            else "#757575"
        entry = (
            f'<font color="#2D2D2D"><b>{i:02d}.</b></font>  '
            f'{title}  '
            f'<font color="{diff_color}"><i>[{diff}]</i></font>'
        )
        story.append(Paragraph(entry, styles["toc_entry"]))

    story.append(PageBreak())


def build_article_section(story: list, styles: dict, article: dict, index: int):
    """Build one article's content block."""
    w, _ = A4
    col_w = w - 4*cm

    elements = []

    # ── Article header bar ──
    num_data = [[Paragraph(f"{index:02d}", styles["article_num"])]]
    num_table = Table(num_data, colWidths=[1.2*cm], rowHeights=[1.2*cm])
    num_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), GFG_GREEN),
        ("ALIGN", (0, 0), (-1, -1), "CENTER"),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("ROUNDEDCORNERS", [4, 4, 4, 4]),
    ]))

    title_text = article.get("title", "Untitled Article")
    title_para = Paragraph(title_text, styles["article_title"])

    header_data = [[num_table, title_para]]
    header_table = Table(header_data, colWidths=[1.5*cm, col_w - 1.5*cm])
    header_table.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("LEFTPADDING", (0, 0), (-1, -1), 0),
        ("RIGHTPADDING", (0, 0), (-1, -1), 0),
        ("TOPPADDING", (0, 0), (-1, -1), 0),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]))
    elements.append(header_table)

    # Difficulty badge
    diff = article.get("difficulty", "Not Available")
    diff_style = difficulty_style(diff, styles)
    elements.append(Paragraph(f"Difficulty Level:  {diff}", diff_style))
    elements.append(Spacer(1, 4))

    # ── Key Technical Concepts ──
    elements += section_label("Key Technical Concepts", styles)
    concepts = article.get("key_concepts", "Not Available")
    style = styles["na"] if concepts == "Not Available" else styles["body"]
    elements.append(Paragraph(concepts, style))

    # ── Code Snippet ──
    elements += section_label("Code Snippet / Implementation", styles)
    code = article.get("code_snippet", "Not Available")
    if code == "Not Available":
        elements.append(Paragraph("Not Available", styles["na"]))
    else:
        # Escape XML chars for ReportLab
        safe_code = code.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
        code_data = [[Paragraph(safe_code, styles["code"])]]
        code_table = Table(code_data, colWidths=[col_w])
        code_table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), CODE_BG),
            ("ROUNDEDCORNERS", [4, 4, 4, 4]),
            ("TOPPADDING", (0, 0), (-1, -1), 8),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
            ("LEFTPADDING", (0, 0), (-1, -1), 10),
            ("RIGHTPADDING", (0, 0), (-1, -1), 10),
        ]))
        elements.append(code_table)

    # ── Complexity Analysis ──
    elements += section_label("Complexity Analysis", styles)
    complexity = article.get("complexity", "Not Available")
    style = styles["na"] if complexity == "Not Available" else styles["body"]
    elements.append(Paragraph(complexity, style))

    # ── References / Related Links ──
    elements += section_label("References / Related Links", styles)
    links = article.get("related_links", "Not Available")
    if links == "Not Available":
        elements.append(Paragraph("Not Available", styles["na"]))
    else:
        for link in links.split("; "):
            link = link.strip()
            if link:
                elements.append(Paragraph(f"• {link}", styles["url"]))

    # ── Source URL ──
    url = article.get("url", "")
    if url:
        elements.append(Spacer(1, 4))
        elements.append(Paragraph(f"Source: {url}", styles["url"]))

    # Bottom separator
    elements.append(Spacer(1, 6))
    elements.append(HRFlowable(width="100%", thickness=0.8, color=BORDER_COLOR))
    elements.append(Spacer(1, 8))

    story.append(KeepTogether(elements[:6]))  # Keep header together
    story.extend(elements[6:])


def generate_pdf(articles: list[dict], output_path: str, student_name: str = "Student") -> str:
    """
    Generate a professional academic PDF learning module.
    Returns the output file path.
    """
    os.makedirs(os.path.dirname(output_path), exist_ok=True)

    date_str = datetime.now().strftime("%B %d, %Y")
    page_cb = PageTemplate(student_name, len(articles))

    doc = SimpleDocTemplate(
        output_path,
        pagesize=A4,
        leftMargin=2*cm,
        rightMargin=2*cm,
        topMargin=3.5*cm,
        bottomMargin=2.2*cm,
        title="GFG PHP Learning Module",
        author=student_name,
        subject="PHP Programming",
    )

    styles = build_styles()
    story = []

    # Cover page (no header/footer)
    build_cover_page(story, styles, student_name, len(articles), date_str)

    # Table of Contents
    build_toc(story, styles, articles)

    # Article sections
    for i, article in enumerate(articles, 1):
        build_article_section(story, styles, article, i)
        if i < len(articles):
            story.append(PageBreak())

    doc.build(story, onFirstPage=page_cb, onLaterPages=page_cb)
    return output_path


